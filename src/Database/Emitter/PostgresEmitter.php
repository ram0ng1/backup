namespace Ramon\Backup\Database\Emitter;

use Ramon\Backup\Database\Dialect;
use Ramon\Backup\Database\Schema\Column;
use Ramon\Backup\Database\Schema\ColumnType;
use Ramon\Backup\Database\Schema\Table;

/**
 * Emitter para PostgreSQL 10+, sem precisar de superuser (RDS, Neon,
 * Supabase) e tolerante a dados sujos vindos do MySQL:
 *
 *   - FKs saem como `ALTER TABLE ADD CONSTRAINT ... NOT VALID` depois dos
 *     dados, nunca no CREATE TABLE: as tabelas saem em ordem alfabética, e
 *     o MySQL aceita linhas órfãs com `FOREIGN_KEY_CHECKS=0`.
 *   - Auto-increment vira `GENERATED BY DEFAULT AS IDENTITY`; a sequência
 *     é reajustada em `emitPostDataFixups()`.
 *   - Nomes de índice são únicos por schema no PG (por tabela no MySQL),
 *     então recebem o prefixo `<table>__` quando ainda não o têm.
 *   - ENUM vira TEXT sem CHECK: o MySQL guarda valores fora da lista, e
 *     o CHECK derrubaria o lote inteiro.
 *   - Índices FULLTEXT/SPATIAL e btree sobre TEXT/BLOB são pulados: o PG
 *     recusa linhas com valor indexado acima de ~2704 bytes, e o MySQL
 *     indexa só um prefixo. Os dados chegam inteiros.
 */
class PostgresEmitter extends AbstractEmitter
{
    /** @var list<string> Avisos de tradução deste emitter. */
    private array $warnings = [];

    /**
     * Por enquanto, só índices pulados. Aparecem junto dos avisos do
     * introspector no progresso do export.
     *
     * @return list<string>
     */
    public function warnings(): array
    {
        return $this->warnings;
    }

    protected function identQuote(): string
    {
        return '"';
    }

    protected function dropTableSuffix(): string
    {
        // CASCADE leva junto as FKs que apontam para cá, em qualquer ordem de DROP.
        return ' CASCADE';
    }

    /**
     * No PostgreSQL o literal partido precisa continuar um literal só (sem
     * tipo), senão `'a' || 'b'` vira `text` e o INSERT numa coluna jsonb
     * falha. A string de escape `E'…'` resolve: o `E` de `END` sai como o
     * octal `\105` e o separador some do texto do dump.
     */
    protected function quoteString(string $value): string
    {
        if (! str_contains($value, '@@END@@')) {
            return $this->quoteLiteral($value);
        }

        $escaped = str_replace(['\\', "'"], ['\\\\', "''"], $value);

        return "E'" . str_replace('@@END@@', '@@\\105ND@@', $escaped) . "'";
    }

    public function targetTag(): string
    {
        return Dialect::POSTGRES->value;
    }

    public function preamble(): string
    {
        $now = gmdate('Y-m-d H:i:s');
        return implode($this->delimiter(), [
            "-- Flarum backup — database dump (target: postgres)",
            "-- Generated at $now UTC",
            "SET client_encoding = 'UTF8'",
            "SET standard_conforming_strings = on",
        ]) . $this->delimiter();
    }

    public function epilogue(): string
    {
        // Nada a desfazer: as FKs já voltaram em emitPostDataFixups.
        return '';
    }

    public function emitSchema(Table $table): string
    {
        $name = $this->quoteIdent($table->name);

        // FKs ficam FORA do CREATE TABLE: o PG exige que a tabela referenciada
        // exista, e uma filha pode vir antes do pai na ordem alfabética. Voltam
        // por ALTER TABLE em emitPostDataFixups.
        $lines = [];
        foreach ($table->columns as $col) {
            $lines[] = '  ' . $this->columnDdl($col);
        }
        if (! empty($table->primaryKey)) {
            $lines[] = '  PRIMARY KEY (' . $this->columnList($table->primaryKey) . ')';
        }

        $body = implode(",\n", $lines);
        $create = "CREATE TABLE $name (\n$body\n)";
        $create = preg_replace('/\s+/', ' ', $create);

        // O DROP ... CASCADE sai antes, no dumper (ver SqlEmitter::emitDropTable).
        $sql = $create . $this->delimiter();

        // No PG os nomes de índice são únicos no schema inteiro, então ganham o
        // prefixo da tabela quando não o têm (o padrão do Laravel já tem).
        // FULLTEXT/SPATIAL e btree sobre TEXT/BLOB são pulados com aviso; os
        // dados chegam inteiros, só o índice fica de fora.
        foreach ($table->indexes as $idx) {
            if ($idx->primary) continue;

            $skipReason = $this->indexSkipReason($table, $idx);
            if ($skipReason !== null) {
                $this->warnings[] = sprintf(
                    'Index `%s`.`%s` skipped on PostgreSQL: %s. The underlying data is preserved; if you rely on this index for queries, recreate it manually with a tailored expression (e.g. `md5(col)` for equality lookups, or a GIN tsvector index for full-text search).',
                    $table->name,
                    $idx->name,
                    $skipReason,
                );
                continue;
            }

            $unique  = $idx->unique ? 'UNIQUE ' : '';
            $idxName = $this->namespacedIndexName($table->name, $idx->name);
            $sql .= 'CREATE ' . $unique . 'INDEX ' . $this->quoteIdent($idxName)
                . ' ON ' . $name . ' (' . $this->columnList($idx->columns) . ')'
                . $this->delimiter();
        }
        return $sql;
    }

    /**
     * Motivo para o índice não poder ser criado no PG, ou null. FULLTEXT e
     * SPATIAL não têm equivalente; btree sobre TEXT/BLOB recusa valores acima
     * de ~2704 bytes, onde o MySQL indexaria só um prefixo.
     */
    private function indexSkipReason(Table $table, \Ramon\Backup\Database\Schema\Index $idx): ?string
    {
        $kind = strtoupper((string) ($idx->kind ?? ''));
        if ($kind === 'FULLTEXT') {
            return 'FULLTEXT indexes are MySQL-specific';
        }
        if ($kind === 'SPATIAL') {
            return 'SPATIAL indexes require PostGIS, not portable';
        }

        // TEXT/BLOB sem limite passam de ~2704 bytes; VARCHAR/CHAR são limitados
        // pelo tamanho declarado e ENUM é curto.
        $unsafe = [
            ColumnType::TEXT, ColumnType::MEDIUMTEXT, ColumnType::LONGTEXT,
            ColumnType::BLOB, ColumnType::MEDIUMBLOB, ColumnType::LONGBLOB,
        ];
        foreach ($idx->columns as $colName) {
            $col = $table->column($colName);
            if ($col !== null && in_array($col->type, $unsafe, true)) {
                return sprintf(
                    'btree indexes over %s columns can exceed PG\'s 2704-byte index-tuple limit',
                    strtoupper($col->type->value)
                );
            }
        }
        return null;
    }

    /**
     * Prefixa `<table>__` quando o nome ainda não começa pela tabela, para
     * nomes curtos repetidos (`card_id`, `user_id`) não colidirem no schema.
     */
    private function namespacedIndexName(string $table, string $idxName): string
    {
        if (str_starts_with($idxName, $table . '_')) {
            return $idxName;
        }
        return $table . '__' . $idxName;
    }

    public function emitInserts(Table $table, array $rows): string
    {
        if (empty($rows)) return '';
        $name = $this->quoteIdent($table->name);
        $columns = array_map(fn (Column $c) => $c->name, $table->columns);
        $colList = $this->columnList($columns);

        $valueGroups = [];
        foreach ($rows as $row) {
            $vals = [];
            foreach ($table->columns as $col) {
                $vals[] = $this->quoteValue($col, $row[$col->name] ?? null);
            }
            $valueGroups[] = '(' . implode(',', $vals) . ')';
        }

        return 'INSERT INTO ' . $name . ' (' . $colList . ') VALUES '
            . implode(',', $valueGroups) . $this->delimiter();
    }

    /**
     * Roda depois dos dados da tabela:
     *
     *   1. FKs, agora que a tabela referenciada existe. ON DELETE / ON UPDATE
     *      vêm da origem.
     *   2. Reajuste da sequência: inserts com id explícito deixam a IDENTITY
     *      em 1, e o próximo INSERT sem id colidiria. `pg_get_serial_sequence`
     *      cobre SERIAL e IDENTITY; o COALESCE trata tabela vazia.
     */
    public function emitPostDataFixups(Table $table): string
    {
        $sql = '';
        $tbl = $this->quoteIdent($table->name);

        foreach ($table->foreignKeys as $fk) {
            $sql .= 'ALTER TABLE ' . $tbl
                . ' ADD CONSTRAINT ' . $this->quoteIdent($fk->name)
                . ' FOREIGN KEY (' . $this->columnList($fk->columns) . ')'
                . ' REFERENCES ' . $this->quoteIdent($fk->refTable)
                . ' (' . $this->columnList($fk->refColumns) . ')';
            if ($fk->onDelete) $sql .= ' ON DELETE ' . $fk->onDelete;
            if ($fk->onUpdate) $sql .= ' ON UPDATE ' . $fk->onUpdate;
            // `NOT VALID` não confere as linhas já carregadas, que podem ter órfãs
            // vindas do MySQL; só escritas novas são validadas. Para validar tudo,
            // `ALTER TABLE ... VALIDATE CONSTRAINT ...` depois de limpar as órfãs.
            $sql .= ' NOT VALID' . $this->delimiter();
        }

        foreach ($table->autoIncrementColumns() as $col) {
            $tableLit = $this->quoteString($table->name);
            $colLit   = $this->quoteString($col);
            $c        = $this->quoteIdent($col);
            $sql .= "SELECT setval(pg_get_serial_sequence($tableLit, $colLit), "
                  . "COALESCE((SELECT MAX($c) FROM $tbl), 0) + 1, false)"
                  . $this->delimiter();
        }
        return $sql;
    }

    /** @param list<string> $columns */
    private function columnList(array $columns): string
    {
        return implode(', ', array_map(fn ($c) => $this->quoteIdent($c), $columns));
    }

    private function columnDdl(Column $col): string
    {
        $sql = $this->quoteIdent($col->name) . ' ' . $this->columnTypeSql($col);
        if ($col->autoIncrement) {
            $sql .= ' GENERATED BY DEFAULT AS IDENTITY';
        }
        // IDENTITY já é NOT NULL; ` NULL` junto dá "conflicting NULL/NOT NULL
        // declarations". Força NOT NULL mesmo se o modelo disser anulável.
        $sql .= ($col->nullable && ! $col->autoIncrement) ? ' NULL' : ' NOT NULL';

        if (! $col->autoIncrement && ($col->default !== null || $col->defaultIsExpression)) {
            $sql .= ' DEFAULT ' . $this->renderDefault($col);
        }
        // ENUM vira TEXT sem CHECK: o MySQL guarda valores fora da lista, e o
        // CHECK derrubaria o lote inteiro. O introspector registra a lista
        // original como aviso.
        return $sql;
    }

    private function columnTypeSql(Column $col): string
    {
        return match ($col->type) {
            ColumnType::BOOL       => 'BOOLEAN',
            ColumnType::TINYINT    => 'SMALLINT',
            ColumnType::SMALLINT   => 'SMALLINT',
            ColumnType::INTEGER    => 'INTEGER',
            ColumnType::BIGINT     => 'BIGINT',
            ColumnType::DECIMAL    => 'NUMERIC(' . ($col->precision ?? 10) . ',' . ($col->scale ?? 0) . ')',
            ColumnType::FLOAT      => 'REAL',
            ColumnType::DOUBLE     => 'DOUBLE PRECISION',
            ColumnType::CHAR       => 'CHAR(' . ($col->length ?? 1) . ')',
            ColumnType::VARCHAR    => 'VARCHAR(' . ($col->length ?? 255) . ')',
            ColumnType::TEXT,
            ColumnType::MEDIUMTEXT,
            ColumnType::LONGTEXT,
            ColumnType::ENUM       => 'TEXT',
            ColumnType::BINARY,
            ColumnType::VARBINARY,
            ColumnType::BLOB,
            ColumnType::MEDIUMBLOB,
            ColumnType::LONGBLOB   => 'BYTEA',
            ColumnType::DATE       => 'DATE',
            ColumnType::TIME       => 'TIME',
            ColumnType::DATETIME   => 'TIMESTAMP',
            ColumnType::TIMESTAMP  => 'TIMESTAMP',
            ColumnType::JSON       => 'JSONB',
            ColumnType::UUID       => 'UUID',
        };
    }

    private function renderDefault(Column $col): string
    {
        if ($col->defaultIsExpression && $col->default !== null) {
            return $col->default;
        }
        if ($col->default === null) {
            return 'NULL';
        }
        if ($col->type === ColumnType::BOOL) {
            return in_array(strtolower($col->default), ['1', 'true', 't'], true) ? 'TRUE' : 'FALSE';
        }
        if ($col->type->isInteger() || in_array($col->type, [ColumnType::FLOAT, ColumnType::DOUBLE, ColumnType::DECIMAL], true)) {
            return is_numeric($col->default) ? $col->default : '0';
        }
        return $this->quoteString($col->default);
    }

    private function quoteValue(Column $col, mixed $value): string
    {
        if ($value === null) return 'NULL';

        if ($col->type === ColumnType::BOOL) {
            if (is_bool($value)) return $value ? 'TRUE' : 'FALSE';
            if (is_numeric($value)) return ((int) $value) ? 'TRUE' : 'FALSE';
            $s = strtolower((string) $value);
            return in_array($s, ['1', 'true', 't'], true) ? 'TRUE' : 'FALSE';
        }

        if ($col->type->isInteger()) {
            if (is_bool($value)) return $value ? '1' : '0';
            return (string) (is_numeric($value) ? $value : 0);
        }

        if (in_array($col->type, [ColumnType::FLOAT, ColumnType::DOUBLE, ColumnType::DECIMAL], true)) {
            return is_numeric($value) ? (string) $value : '0';
        }

        if ($col->type->isBinary()) {
            $bytes = is_resource($value) ? (stream_get_contents($value) ?: '') : (string) $value;
            // Literal hex de bytea: '\xDEADBEEF'
            return $this->quoteString('\\x' . bin2hex($bytes));
        }

        if ($col->type === ColumnType::JSON) {
            // JSON chega já codificado (string) ou como array (o PG devolve
            // decodificado); sai sempre como literal string, que o jsonb reinterpreta.
            $s = is_string($value) ? $value : json_encode($value, JSON_UNESCAPED_UNICODE);
            return $this->quoteString((string) $s);
        }

        if (! is_string($value)) {
            $value = (string) $value;
        }
        return $this->quoteString($value);
    }
}
